-- Notice2Action AI - initial PostgreSQL schema (Supabase compatible)
--
-- Idempotent: safe to run more than once (CREATE ... IF NOT EXISTS).
-- Apply with the Supabase SQL Editor, `supabase db push`, or `python db_tools.py init`.
--
-- Data model (same as the SQLite version):
--   notices (1) ---< deadlines (n)
--   notices (1) ---< action_items (n) >--- (0..1) deadlines
-- Deleting a notice cascades to its deadlines and action items.

-- ---------------------------------------------------------------------------
-- notices
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.notices (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             TEXT        NOT NULL CHECK (length(btrim(title)) > 0),
    category          TEXT        NOT NULL DEFAULT 'Other',
    summary           TEXT,
    organization      TEXT,
    department        TEXT,
    announcement_date DATE,
    venue             TEXT,
    source_language   TEXT,
    file_name         TEXT,
    content_hash      TEXT        NOT NULL UNIQUE,          -- SHA-256 of normalised text: duplicate detection
    extracted_text    TEXT,
    analysis_json     JSONB       NOT NULL,                 -- full validated AI analysis
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- deadlines
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.deadlines (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notice_id     BIGINT      NOT NULL REFERENCES public.notices(id) ON DELETE CASCADE,
    description   TEXT        NOT NULL,
    deadline_date DATE,                                      -- NULL when the notice gives no date
    deadline_time TEXT,                                      -- free text, e.g. '17:00' or '5 PM'
    date_type     TEXT        NOT NULL DEFAULT 'unspecified'
                  CHECK (date_type IN ('explicit', 'inferred', 'unspecified')),
    source_text   TEXT,                                      -- supporting sentence from the notice
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- action_items (tasks)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.action_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notice_id     BIGINT      NOT NULL REFERENCES public.notices(id) ON DELETE CASCADE,
    deadline_id   BIGINT      REFERENCES public.deadlines(id) ON DELETE SET NULL,
    title         TEXT        NOT NULL CHECK (length(btrim(title)) > 0),
    description   TEXT,
    priority      TEXT        NOT NULL DEFAULT 'medium'
                  CHECK (priority IN ('high', 'medium', 'low')),
    status        TEXT        NOT NULL DEFAULT 'pending'
                  CHECK (status IN ('pending', 'completed')),
    due_date      DATE,
    due_date_type TEXT        NOT NULL DEFAULT 'none'
                  CHECK (due_date_type IN ('explicit', 'inferred', 'manual', 'none')),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at  TIMESTAMPTZ
);

-- ---------------------------------------------------------------------------
-- indexes for the app's common queries
-- ---------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_notices_created_at  ON public.notices (created_at DESC);   -- library ordering / date filter
CREATE INDEX IF NOT EXISTS idx_notices_category    ON public.notices (category);          -- category filter + dashboard chart
CREATE INDEX IF NOT EXISTS idx_deadlines_notice    ON public.deadlines (notice_id);       -- FK / cascade
CREATE INDEX IF NOT EXISTS idx_deadlines_date      ON public.deadlines (deadline_date)
    WHERE deadline_date IS NOT NULL;                                                      -- upcoming deadlines
CREATE INDEX IF NOT EXISTS idx_actions_notice      ON public.action_items (notice_id);    -- FK / cascade
CREATE INDEX IF NOT EXISTS idx_actions_deadline    ON public.action_items (deadline_id);  -- FK (SET NULL)
CREATE INDEX IF NOT EXISTS idx_actions_status      ON public.action_items (status);       -- pending/completed counts
CREATE INDEX IF NOT EXISTS idx_actions_due_date    ON public.action_items (due_date)
    WHERE due_date IS NOT NULL;                                                           -- overdue / due soon

-- ---------------------------------------------------------------------------
-- security: lock the tables away from Supabase's public REST/GraphQL API.
--
-- Supabase exposes every table in the `public` schema through the Data API using
-- the (public) anon key. The app connects server-side as the database owner, which
-- bypasses RLS, so we enable RLS with NO policies (deny all) and revoke grants from
-- the API roles. Nothing can read or write these tables through the API.
-- ---------------------------------------------------------------------------
ALTER TABLE public.notices      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.deadlines    ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.action_items ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON public.notices, public.deadlines, public.action_items FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON public.notices, public.deadlines, public.action_items FROM authenticated;
    END IF;
END $$;
